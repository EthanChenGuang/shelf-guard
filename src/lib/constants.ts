/** Shelf carousel label chip — full I18N audit in 05-07. */
export function getShelfLabel(lang: Language, shelfIndex: number): string {
  const n = shelfIndex + 1;
  return lang === 'cn' ? `柜架 ${n}` : `Shelf ${n}`;
}

